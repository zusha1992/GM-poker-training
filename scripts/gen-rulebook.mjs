// Copies decisions/price-drill-rulebook.md into src/lib/rulebook-content.ts so
// the /rulebook page can show it on Cloudflare (no file system there).
// Run after every rulebook edit: npm run rulebook
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync("decisions/price-drill-rulebook.md", "utf8").replace(/\r\n/g, "\n");
const out = `// Generated by scripts/gen-rulebook.mjs from decisions/price-drill-rulebook.md. Do not edit by hand.\nexport const RULEBOOK_MD = ${JSON.stringify(md)};\n`;
writeFileSync("src/lib/rulebook-content.ts", out);
console.log(`rulebook-content.ts written (${md.length} chars)`);
