// Writes src/lib/drill/postflop/solver-answers.ts from the solve-board.ts reports
// (every rows-*.json under the TexasSolver runs folder).
// Usage: npx tsx scripts/analysis/solver-answers-gen.ts
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { RUNOUTS } from "../../src/lib/drill/postflop/price-hands";

const RUNS = "C:/Users/noams/Developer/tools/TexasSolver/runs";
type Row = { g: string; ev: number; money: number; bet: number; solver: string | null };
type Rows = { id: string; street: "turn" | "river"; pot: number; rows: Row[] };

const out = new Map<string, Map<string, string[]>>(); // runout id → street → lines
const add = (id: string, street: string, line: string) => {
  const m = out.get(id) ?? new Map<string, string[]>();
  m.set(street, [...(m.get(street) ?? []), line]);
  out.set(id, m);
};
const pct = (x: number) => Math.round(x * 100);
for (const board of readdirSync(RUNS)) {
  if (!existsSync(`${RUNS}/${board}/DONE`)) continue;
  for (const f of readdirSync(`${RUNS}/${board}`).filter((x) => x.startsWith("rows-")).sort()) {
    const r: Rows = JSON.parse(readFileSync(`${RUNS}/${board}/${f}`, "utf8"));
    const spec = RUNOUTS.find((x) => x.id === r.id)!;
    // A turn is shared by both of its runouts.
    const ids = r.street === "turn" ? RUNOUTS.filter((x) => x.board === spec.board && x.streets[1].card === spec.streets[1].card).map((x) => x.id) : [r.id];
    for (const row of r.rows) {
      if (!row.solver) continue;
      // Noam 2026-11-07 (986), 2026-11-08 (every board, as a draft to review board by board): a made hand
      // that wins back under 15% of the pot has almost no showdown value, so the pot is too big for it
      // (whether the solver bets it doesn't matter). Turn and river only: on the flop every pair still has equity.
      if (row.ev < 0.15 * r.pot) {
        const why = `wins back only ${pct(row.ev / r.pot)}% of the ${r.pot}bb pot (EV ${row.ev.toFixed(1)}bb): almost no showdown value, so the pot is too big for it.`;
        for (const id of ids) add(id, r.street, `      ${row.g}: s("big", "${why}"),`);
        continue;
      }
      const bets = row.bet < 0.02 ? "checks" : `bets ${pct(row.bet)}% of the time, about ${row.money.toFixed(0)}bb on average`;
      const bluff = r.street === "river" && row.solver === "b0" && row.bet >= 0.3;
      const why = bluff
        ? `${bets}, but as a bluff (EV only ${row.ev.toFixed(0)}bb): what it's worth is 0–5bb.`
        : r.street === "river" ? `${bets}.` : `EV about ${row.ev.toFixed(1)}bb once BB checks (pot ${r.pot}bb); ${bets}.`;
      for (const id of ids) add(id, r.street, `      ${row.g}: s("${row.solver}", "${why}"),`);
    }
  }
}

const body = [...out]
  .sort((a, b) => RUNOUTS.findIndex((x) => x.id === a[0]) - RUNOUTS.findIndex((x) => x.id === b[0]))
  .map(([id, streets]) => `  "${id}": {\n${[...streets].map(([st, lines]) => `    ${st}: {\n${lines.join("\n")}\n    },`).join("\n")}\n  },`)
  .join("\n");

writeFileSync(
  "src/lib/drill/postflop/solver-answers.ts",
  `/**
 * "How many bb" answers from our own TexasSolver solves (Noam 2026-11-05/06),
 * generated by scripts/analysis/solver-answers-gen.ts; don't edit by hand.
 * Each board is solved street by street in the drill's line: BTN bets 33% on
 * the flop, 66% or 150% on the turn; BB's range on each street is what it
 * checks and calls with in the solve before (scripts/analysis/solve-board.ts).
 *
 * Pair-or-better groups only; draws and no-pair hands keep their rules (the
 * drill asks what a group is worth).
 * - Turn: the group's EV once BB checks, with the flop cut-offs (6.2 / 4.5 /
 *   3.4bb at a 5.5bb pot, from GTO Wizard's A72 flop) scaled to the pot.
 * - River: what the group bets on average once BB checks (frequency × size),
 *   if it bets at least 30% of the time; otherwise 0–5bb.
 * These answers win over the rule-based ones.
 */
import type { Answer, Bucket, PGroup } from "./price-hands";

const s = (bucket: Bucket, why: string): Answer => ({ bucket, why: \`TexasSolver: \${why}\`, sure: false });

/** Keyed by runout id ("A72 · Q♥ · 9♣") and street. */
export const SOLVER_ANSWERS: Record<string, Partial<Record<"flop" | "turn" | "river", Partial<Record<PGroup, Answer>>>>> = {
${body}
};
`,
);
console.log(`${out.size} runouts`);
