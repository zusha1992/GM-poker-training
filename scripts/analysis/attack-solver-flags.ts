// Attack drill, accuracy check (Noam & Uri 2026-11-20): where our solver's EV disagrees with the
// drill's box. Reads every board's solver report (runs/<board>/report.txt, written by solve-board.ts:
// per hand category, BTN's EV, how often it bets, and the box that EV points to) and lists the
// categories whose solver box is two or more boxes away from the drill's. Noam and Uri review only these.
// Writes decisions/attack-solver-flags.md.
// Usage: npx tsx scripts/analysis/attack-solver-flags.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { BOARDS } from "../../src/lib/drill/postflop/price-hands";

const RUNS = "C:/Users/noams/Developer/tools/TexasSolver/runs";
const RANK: Record<string, number> = { big: -1, b0: 0, b5: 1, b15: 2, b25: 3, b50: 4 };
const NAME: Record<string, string> = { big: "Check, give up", b0: "One small bet (0–5)", b5: "Two bets (5–15)", b15: "Three small bets (15–25)", b25: "Three bets (25–50)", b50: "All in (50–100)" };

const out = [
  "# Attack drill: where the solver disagrees",
  "",
  "For each solved spot, the hand categories whose box from our solver's EV is **two or more boxes** away from the drill's box. Everything else agrees within one box. These are the groups for Noam and Uri to look at first. Note: the report's “drill box” is the answer of the full-hand drill when the spot was solved (by poker category); the current Flop / Turn / River groups are made by equity and reviews, so read a flag as “look here”, not as a verdict. Source: `runs/<board>/report.txt` (TexasSolver, solve-board.ts); generated by `scripts/analysis/attack-solver-flags.ts`.",
  "",
  "| Spot | Category | Hands | Solver EV | Solver bets | Drill box | Solver's box |",
  "|---|---|---|---|---|---|---|",
];
let flagged = 0, checked = 0;
for (const b of BOARDS) {
  const f = `${RUNS}/${b.name}/report.txt`;
  if (!existsSync(f)) continue;
  let spot = b.name;
  for (const line of readFileSync(f, "utf8").split(/\r?\n/)) {
    const head = line.match(/^== (turn|river) (.+?)(?: \(|$)/);
    if (head) {
      spot = `${b.name} ${head[1] === "turn" ? "turn" : "river"} ${head[2]}`;
      continue;
    }
    const m = line.match(/^(\w+)\s+(.+?)\s+EV\s+([\d.]+)bb\s+bets\s+(\d+)%.*drill (\w+)(?:\s+→ (\w+))?/);
    if (!m) continue;
    checked++;
    const [, , hands, ev, bets, drill, solver] = m;
    if (!solver || Math.abs(RANK[solver] - RANK[drill]) < 2) continue;
    flagged++;
    out.push(`| ${spot} | ⚠ ${m[1]} | ${hands} | ${ev}bb | ${bets}% | ${NAME[drill]} | ${NAME[solver]} |`);
  }
}
out.push("", `${flagged} of ${checked} categories flagged.`, "");
writeFileSync("decisions/attack-solver-flags.md", out.join("\n"));
console.log(`${flagged} of ${checked} categories flagged`);
