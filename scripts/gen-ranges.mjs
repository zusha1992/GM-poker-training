// Copies the hand-by-hand solver reads (decisions/ranges/<drill>/<spot>.txt,
// written by the range-from-screenshots skill) into src/lib/drill/preflop/solver-reads.ts
// so the drills can use them on Cloudflare (no file system there).
// Run after every read edit: npm run ranges
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = "decisions/ranges";
const reads = {};
for (const drill of readdirSync(ROOT)) {
  for (const file of readdirSync(`${ROOT}/${drill}`).filter((f) => f.endsWith(".txt"))) {
    const hands = {};
    for (const raw of readFileSync(`${ROOT}/${drill}/${file}`, "utf8").split(/\r?\n/)) {
      const line = raw.replace(/#.*/, "").trim();
      if (!line) continue;
      const [hand, ...nums] = line.split(/\s+/);
      hands[hand] = nums.map(Number);
    }
    reads[`${drill}/${file.replace(/\.txt$/, "")}`] = hands;
  }
}
const body = Object.entries(reads)
  .map(([spot, hands]) => `  ${JSON.stringify(spot)}: {\n${Object.entries(hands).map(([h, v]) => `    ${JSON.stringify(h)}: ${JSON.stringify(v)},`).join("\n")}\n  },`)
  .join("\n");
const out =
  `// Generated by scripts/gen-ranges.mjs from decisions/ranges/. Do not edit by hand.\n` +
  `// Per spot, per hand: [aggressive %, call %, fold %]. Hands left out are pure folds.\n` +
  `export const SOLVER_READS: Record<string, Record<string, [number, number, number]>> = {\n${body}\n};\n`;
writeFileSync("src/lib/drill/preflop/solver-reads.ts", out);
console.log(`solver-reads.ts written (${Object.keys(reads).length} spots)`);
